const CACHE_NAME = "quiz-cache-660d0bb"; // version automatique

// helper shared by install and message handler
function cacheAllAssets() {
  return caches.open(CACHE_NAME).then((cache) => {
    const total = STATIC_ASSETS.length;
    let completed = 0;

    // notify start
    self.clients.matchAll({ includeUncontrolled: true }).then((clients) => {
      clients.forEach((c) => c.postMessage({ type: "caching-start", total }));
    });

    // fetch each asset and report progress
    return Promise.all(
      STATIC_ASSETS.map((url) =>
        fetch(url, { cache: "no-cache" })
          .then((res) => {
            if (res.ok) return cache.put(url, res);
          })
          .catch(() => {})
          .finally(() => {
            completed++;
            self.clients
              .matchAll({ includeUncontrolled: true })
              .then((clients) => {
                clients.forEach((c) =>
                  c.postMessage({
                    type: "caching-progress",
                    completed,
                    total,
                  }),
                );
              });
          }),
      ),
    ).then(() => {
      self.clients.matchAll({ includeUncontrolled: true }).then((clients) => {
        clients.forEach((c) => c.postMessage({ type: "caching-complete" }));
      });
    });
  });
}

self.addEventListener("install", (event) => {
  self.skipWaiting();
  event.waitUntil(cacheAllAssets());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

// respond to messages from clients (e.g. page asking to recache assets)
self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "cache-assets") {
    cacheAllAssets();
  }
});

self.addEventListener("fetch", (event) => {
  // Navigation requests: try network first, cache response, then cache fallback
  if (event.request.mode === "navigate") {
    event.respondWith(
      fetch(event.request).then((response) => {
        if (response.ok) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        }
        return response;
      }).catch(() => {
        return caches.match(event.request).then((cachedResponse) => {
          return (
            cachedResponse ||
            caches.match("./index.html") ||
            caches.match("./offline.html")
          );
        });
      }),
    );
    return;
  }

  // Other requests: cache first, then network + cache response
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request).then((response) => {
        if (response.ok) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        }
        return response;
      });
    }),
  );
});
